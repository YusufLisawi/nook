#!/usr/bin/env python3
"""Build Nook/Resources/places.tsv (place name -> IANA time zone -> label) for the launcher's time answers.

Data: GeoNames (https://www.geonames.org, CC BY 4.0) — cities15000.txt + countryInfo.txt from
https://download.geonames.org/export/dump/. Usage: scripts/gen-places.py <dir with both files>
"""
import os, sys, unicodedata

src = sys.argv[1]
countries = {}
for line in open(os.path.join(src, "countryInfo.txt"), encoding="utf-8"):
    if line.startswith("#"):
        continue
    f = line.rstrip("\n").split("\t")
    if len(f) > 5:
        countries[f[0]] = f[4]

def fold(s):
    s = unicodedata.normalize("NFKD", s)
    return "".join(c for c in s if not unicodedata.combining(c)).lower().strip()

best = {}       # name -> (population, tz, label)
alts_locked = set()
country_tz = {} # country name -> (population, tz)
for line in open(os.path.join(src, "cities15000.txt"), encoding="utf-8"):
    f = line.rstrip("\n").split("\t")
    name, ascii_name, cc, pop, tz = f[1], f[2], f[8], int(f[14] or 0), f[17]
    if not tz:
        continue
    country = countries.get(cc, cc)
    for key in {fold(name), fold(ascii_name)}:
        if key and (key not in best or key not in alts_locked or pop > best[key][0]):
            best[key] = (pop, tz, country)
            alts_locked.add(key)
    # Common short/alternate names ("Frankfurt" for "Frankfurt am Main") for bigger cities, never overriding real names.
    if pop >= 100_000:
        for alt in f[3].split(","):
            key = fold(alt)
            if 3 <= len(key) <= 30 and all(c.isascii() and (c.isalpha() or c in " -'.") for c in key):
                if key not in best or (best[key][0] < pop and key not in alts_locked):
                    best[key] = (pop, tz, country)
    ck = fold(country)
    if ck not in country_tz or pop > country_tz[ck][0]:
        country_tz[ck] = (pop, tz)

out = {}
for key, (pop, tz, label) in best.items():
    out[key] = (tz, label)
for key, (pop, tz) in country_tz.items():  # a country name means its biggest city's zone
    out[key] = (tz, next(v for k, v in countries.items() if fold(v) == key) if any(fold(v) == key for v in countries.values()) else key)

dest = os.path.join(os.path.dirname(__file__), "..", "Nook", "Resources", "places.tsv")
with open(dest, "w", encoding="utf-8") as fh:
    fh.write("# GeoNames (geonames.org) CC BY 4.0 — generated by scripts/gen-places.py\n")
    for key in sorted(out):
        tz, label = out[key]
        fh.write(f"{key}\t{tz}\t{label}\n")
print(len(out), "places ->", os.path.normpath(dest))
